#include <iostream>

using namespace std;

int main()
{
    int i = 1;
    double d = 0.2;
    char c = 'A';
    bool b = true;

    cout << "iの値は" << i << endl;
    cout << "dの値は" << d << endl;
    cout << "cの値は" << c << endl;
    cout << "bの値は" << b << endl;

    int j = 1.99;
    double e = 1.99;
    cout << "jの値は" << j << endl;
    cout << "eの値は" << e;
}
